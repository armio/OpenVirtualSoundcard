//! A one-line text field, for the device's name.
//!
//! Adapted from the text input example of GPUI (`examples/input.rs` of the
//! `gpui` crate 0.2.2, in the Zed repository), Copyright Zed Industries,
//! Inc., licensed under the Apache License 2.0. Changed here: a limit on
//! the number of characters, Return to submit, an event for each edit, the
//! app's colours, and a red edge for a name with a problem.

use std::ops::Range;

